#!/usr/bin/env bash
# Task 2.5–2.6 — settlement details via transient field into collectionSettlementDetails and proof that the
# original values are neither in the transaction arguments nor in the public part of the ledger.
# Synthetic, checksum-valid test data (bank code 999, "TEST", "SYNTHETIC") — not real accounts.
set -euo pipefail
source "$(dirname "$0")/lib.sh"
CSV="$EVIDENCE/task2/txids.csv"
SECRETS="$ROOT/.secrets"; mkdir -p "$SECRETS"; chmod 700 "$SECRETS"
CLIENT="$ROOT/client/payment-client"
use_org 1 initiator1
RESUME=0
cc_query paymentsecure '{"Args":["PaymentOrderExists","PO-S001"]}' 2>/dev/null | grep -q true && RESUME=1
if (( RESUME )); then
  LOG_APPEND=1 start_log task2 23_private_flow
  info "шаги 1–3 уже выполнены (PO-S001 существует) — TxID из evidence/task2/txids.csv, выполняются проверки 4–8"
else
  start_log task2 23_private_flow
  [[ -f "$CSV" ]] && sed -i '/^S[0-9],/d' "$CSV"
fi

MARKERS=(KZ09999TESTPAYER0001 KZ17999TESTBENEF0002 999999000001 "TOO SYNTHETIC BENEFICIARY" KZ60999TESTBENEF0004)
mask() { local v="$1"; printf '%s%s%s' "${v:0:2}" "$(printf '%*s' $((${#v} - 6)) '' | tr ' ' '*')" "${v: -4}"; }
make_details() { # <file> <beneficiaryIBAN> — salt is generated by the CLIENT (OWASP SC09)
  jq -n --arg b "$2" --arg s "$(openssl rand -hex 32)" \
    '{payerIBAN:"KZ09999TESTPAYER0001", payerBIN:"999999000001", beneficiaryIBAN:$b,
      beneficiaryBIC:"TESTKZKAXXX", beneficiaryName:"TOO SYNTHETIC BENEFICIARY", salt:$s}' >"$1"
  chmod 600 "$1"
}

if (( ! RESUME )); then
step "1. initiator1 (Org1) создаёт PO-S001 — публичная транзакция, endorse обоими peers (AND)"
cc_invoke paymentsecure '{"function":"CreatePaymentOrder","Args":["PO-S001","Org2MSP","870000000","KZT","119","Оплата по контракту 2026/45"]}' || true
grep ClientWait <<<"$TX_OUT" | sed 's/^/  /'
record_tx "$CSV" S1 CreatePaymentOrder '["PO-S001","Org2MSP","870000000","KZT","119","Оплата по контракту 2026/45"]'
show_tx "S1 Create PO-S001"

step "2. SetSettlementDetails(PO-S001): реквизиты ТОЛЬКО в transient, endorse ТОЛЬКО peer0.org1"
make_details "$SECRETS/PO-S001.settlement.json" KZ17999TESTBENEF0002
echo "  реквизиты (маскированы): payerIBAN=$(mask KZ09999TESTPAYER0001) beneficiaryIBAN=$(mask KZ17999TESTBENEF0002) BIN=$(mask 999999000001) salt=<32 байта hex, клиент>"
printf '%s$ peer chaincode invoke -C %s -n paymentsecure -c {"function":"SetSettlementDetails","Args":["PO-S001"]} --peerAddresses localhost:7051 --transient {"settlement":"<base64, не выводится>"}%s\n' "$C_D" "$CHANNEL" "$C_0"
TRANSIENT="{\"settlement\":\"$(base64 -w0 "$SECRETS/PO-S001.settlement.json")\"}"
cc_invoke paymentsecure '{"function":"SetSettlementDetails","Args":["PO-S001"]}' --peers "1" --transient "$TRANSIENT" || true
unset TRANSIENT
grep ClientWait <<<"$TX_OUT" | sed 's/^/  /'
record_tx "$CSV" S2 SetSettlementDetails '["PO-S001"]'
SET_TX="$TXID"
show_tx "S2 SetSettlementDetails PO-S001 (endorser: только peer0.org1, collection EP OR('Org1MSP.peer'))"

step "3. Альтернатива через Fabric Gateway: WithTransient + WithEndorsingOrganizations(Org1MSP)"
cc_invoke paymentsecure '{"function":"CreatePaymentOrder","Args":["PO-S002","Org2MSP","15000000","KZT","119","Оплата услуг связи"]}' || true
record_tx "$CSV" S3 CreatePaymentOrder '["PO-S002","Org2MSP","15000000","KZT","119","Оплата услуг связи"]'
show_tx "S3 Create PO-S002"
make_details "$SECRETS/PO-S002.settlement.json" KZ60999TESTBENEF0004
gw="$(ROOT="$ROOT" "$CLIENT" -org 1 -user initiator1 -endorsing-orgs Org1MSP -transient "settlement=@$SECRETS/PO-S002.settlement.json" \
      submit paymentsecure SetSettlementDetails PO-S002 2>&1)" || true
echo "$gw" | sed 's/^/  /'
TXID="$(awk '/^TxID/ {print $3}' <<<"$gw")"; TX_STATUS="$(awk '/^Status/ {print $3}' <<<"$gw")"
record_tx "$CSV" S4 "SetSettlementDetails (Gateway)" '["PO-S002"]'
show_tx "S4 SetSettlementDetails PO-S002 через Gateway"

fi
SET_TX="${SET_TX:-$(csv_field "$CSV" S2 txid)}"

step "4. Доказательство: аргументы и блок транзакции SetSettlementDetails"
W="$(mktemp -d)"; trap 'rm -rf "$W"' EXIT
peer chaincode query -C "$CHANNEL" -n qscc -c "{\"Args\":[\"GetBlockByTxID\",\"$CHANNEL\",\"$SET_TX\"]}" --hex 2>/dev/null | tr -d '\n' | xxd -r -p >"$W/block.pb"
configtxlator proto_decode --type common.Block --input "$W/block.pb" --output "$W/block.json"
cp "$W/block.json" "$EVIDENCE/task2/23_setsettlement_block_decoded.json"
idx="$(jq -r --arg t "$SET_TX" '[.data.data[].payload.header.channel_header.tx_id] | index($t)' "$W/block.json")"
A=".data.data[$idx].payload.data.actions[0].payload"
echo "  блок #$(jq -r .header.number "$W/block.json"), tx[$idx] $SET_TX"
args="$(jq -r "$A.chaincode_proposal_payload.input.chaincode_spec.input.args[]" "$W/block.json" | while read -r a; do printf '%s ' "$(base64 -d <<<"$a")"; done)"
echo "  аргументы транзакции: $args"
[[ "$args" == "SetSettlementDetails PO-S001 " ]] && ok "аргументы содержат только имя функции и PO-S001"
tm_in_block="$(jq -r "$A.chaincode_proposal_payload.TransientMap // {} | length" "$W/block.json")"
[[ "$tm_in_block" == 0 ]] && ok "TransientMap в блоке отсутствует (peer удаляет transient из proposal payload)"
echo "  ns_rwset:"
jq -r "$A.action.proposal_response_payload.extension.results.ns_rwset[] | \"    namespace=\(.namespace) public_writes=\(.rwset.writes // [] | length) collections=\([.collection_hashed_rwset[]?.collection_name] | join(\",\"))\"" "$W/block.json"
# hashed_rwset is nested serialized bytes -> decode as kvrwset.HashedRWSet
for h in $(jq -r "$A.action.proposal_response_payload.extension.results.ns_rwset[] | select(.namespace==\"paymentsecure\") | .collection_hashed_rwset[]?.hashed_rwset" "$W/block.json"); do
  base64 -d <<<"$h" >"$W/h.pb"
  configtxlator proto_decode --type kvrwset.HashedRWSet --input "$W/h.pb" \
    | jq -r '.hashed_writes[]? | "    hashed write: key_hash=\(.key_hash)  value_hash=\(.value_hash)  is_delete=\(.is_delete // false)"'
done
pubw="$(jq -r "[$A.action.proposal_response_payload.extension.results.ns_rwset[] | select(.namespace==\"paymentsecure\") | .rwset.writes // [] | length] | add" "$W/block.json")"
[[ "$pubw" == 0 ]] && ok "публичных записей нет — только collection_hashed_rwset (хэш ключа и хэш значения)"
ends="$(jq -r "$A.action.endorsements | length" "$W/block.json")"
echo "  endorsements: $ends"
code="$(block_codes "$W/block.json" | sed -n "$((idx + 1))p")"
[[ "$ends" == 1 && "$(validation_code_name "$code")" == VALID ]] && ok "одна endorsement (peer0.org1) и статус VALID — сработала collection-level EP OR('Org1MSP.peer')"

step "5. grep -c маркеров реквизитов: сырой блок (.pb), decoded JSON, все base64-поля блока"
jq -r '.. | strings' "$W/block.json" | while read -r s; do base64 -d <<<"$s" 2>/dev/null || true; echo; done >"$W/deep.txt"
total=0
for m in "${MARKERS[@]}"; do
  a="$(grep -c -a -- "$m" "$W/block.pb" || true)"; b="$(grep -c -- "$m" "$W/block.json" || true)"; c="$(grep -c -a -- "$m" "$W/deep.txt" || true)"
  printf '  %-28s raw.pb=%s  decoded.json=%s  base64-decoded=%s\n' "$(mask "$m")" "$a" "$b" "$c"
  total=$((total + a + b + c))
done
ctl="$(grep -c -a PO-S001 "$W/block.pb" || true)"
echo "  контроль метода: grep -c -a PO-S001 raw.pb = $ctl (открытый аргумент находится)"
(( total == 0 && ctl > 0 )) && ok "реквизиты в блоке: 0 совпадений (метод поиска проверен положительным контролем)"

step "6. CouchDB: базы paymentsecure на peer0.org1 и peer0.org2"
COUCH_USER="$(grep -m1 'COUCHDB_USER=' "$TEST_NETWORK/compose/compose-couch.yaml" | sed 's/.*COUCHDB_USER=//' | tr -d ' "')"
COUCH_PASS="$(grep -m1 'COUCHDB_PASSWORD=' "$TEST_NETWORK/compose/compose-couch.yaml" | sed 's/.*COUCHDB_PASSWORD=//' | tr -d ' "')"
couch() { curl -s -u "$COUCH_USER:$COUCH_PASS" "http://localhost:$1/$2"; }
for p in 5984 7984; do
  peer_name=$([[ $p == 5984 ]] && echo "peer0.org1 (couchdb0:5984)" || echo "peer0.org2 (couchdb1:7984)")
  echo "  $peer_name: $(couch "$p" _all_dbs | jq -r '[.[] | select(startswith("paymentchannel_paymentsecure"))] | join("  ")')"
done
dbs1="$(couch 5984 _all_dbs)"; dbs2="$(couch 7984 _all_dbs)"
pdb="$(jq -r '.[] | select(startswith("paymentchannel_paymentsecure$$p"))' <<<"$dbs1")"
hdb="$(jq -r '.[] | select(startswith("paymentchannel_paymentsecure$$h"))' <<<"$dbs1")"
[[ -n "$pdb" && -n "$hdb" ]] && ok "Org1: есть \$\$p (открытые private data) и \$\$h (хэши)"
[[ -z "$(jq -r '.[] | select(startswith("paymentchannel_paymentsecure$$p"))' <<<"$dbs2")" && -n "$(jq -r '.[] | select(startswith("paymentchannel_paymentsecure$$h"))' <<<"$dbs2")" ]] \
  && ok "Org2: только \$\$h — открытых реквизитов у банка-получателя нет"
enc_h="$(jq -rn --arg d "$hdb" '$d|@uri')"
echo "  пример документа в \$\$h на Org2 (ключ = хэш ключа, значение = хэш значения):"
couch 7984 "$enc_h/_all_docs?limit=2&include_docs=true" | jq -c '.rows[].doc | {_id, valueHash: (.["~version"] // "")} ' | sed 's/^/    /'
org2_hits=0
for m in "${MARKERS[@]}"; do
  n="$(couch 7984 "$enc_h/_all_docs?include_docs=true" | grep -c -- "$m" || true)"; org2_hits=$((org2_hits + n))
  n="$(couch 7984 "paymentchannel_paymentsecure/_all_docs?include_docs=true" | grep -c -- "$m" || true)"; org2_hits=$((org2_hits + n))
done
(( org2_hits == 0 )) && ok "CouchDB Org2 (публичная база + \$\$h): 0 совпадений маркеров"
org1_pub=0
for m in "${MARKERS[@]}"; do
  n="$(couch 5984 "paymentchannel_paymentsecure/_all_docs?include_docs=true" | grep -c -- "$m" || true)"; org1_pub=$((org1_pub + n))
done
(( org1_pub == 0 )) && ok "публичная база paymentsecure на Org1: 0 совпадений (реквизиты только в \$\$p)"
enc_p="$(jq -rn --arg d "$pdb" '$d|@uri')"
pc="$(couch 5984 "$enc_p/_all_docs?include_docs=true" | grep -c KZ09999TESTPAYER0001 || true)"
(( pc > 0 )) && ok "положительный контроль: \$\$p на Org1 содержит реквизиты (значения не выводятся)"
unset COUCH_USER COUCH_PASS

step "7. Логи контейнеров: peer0.org1, peer0.org2, orderer, контейнеры chaincode paymentsecure"
log_hits=0
for c in peer0.org1.example.com peer0.org2.example.com orderer.example.com $(docker ps --format '{{.Names}}' | grep paymentsecure); do
  n=0
  for m in "${MARKERS[@]}"; do k="$(docker logs "$c" 2>&1 | grep -c -- "$m" || true)"; n=$((n + k)); done
  printf '  %-90s %s совпадений\n' "$c" "$n"; log_hits=$((log_hits + n))
done
(( log_hits == 0 )) && ok "логи всех контейнеров: 0 совпадений маркеров реквизитов"

step "8. ReadSettlementDetails от initiator1 на peer0.org1 (в отчёте — маскированно)"
res="$(cc_query paymentsecure '{"Args":["ReadSettlementDetails","PO-S001"]}' --peer 1 2>/dev/null)"
jq -r --arg a "$(mask KZ09999TESTPAYER0001)" --arg b "$(mask KZ17999TESTBENEF0002)" --arg n "$(mask 999999000001)" \
  '"  id=\(.id) payerIBAN=\($a) payerBIN=\($n) beneficiaryIBAN=\($b) beneficiaryBIC=\(.beneficiaryBIC[0:4])**** beneficiaryName=\(.beneficiaryName[0:3])***"' <<<"$res"
[[ "$(jq -r .payerIBAN <<<"$res")" == KZ09999TESTPAYER0001 ]] && ok "Org1 (initiator1) получила реквизиты из private data; соль не возвращается: $(jq 'has("salt")' <<<"$res")"
summary
